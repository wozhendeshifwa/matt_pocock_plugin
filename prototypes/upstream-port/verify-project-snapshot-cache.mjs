import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createProjectSnapshotCache } from './project-snapshot-cache.mjs';

const directory = await mkdtemp(path.join(tmpdir(), 'deck-startup-cache-'));
const workspaceRoot = path.join(directory, 'project-a');
let identity = 'binding-a', time = 1000;
const reply = title => ({ ok: true, value: { ok: true, workspaceRoot, selection: { backendId: 'github' }, maps: [], issues: [{ key: '1', title }], generatedMs: 900, updatedAt: 'original-time' } });
const cache = call => createProjectSnapshotCache({ directory, workspaceRoot, identity: async () => identity, call, now: () => time });
await cache(async () => reply('original')).read('snapshot');
let release;
const blocked = new Promise(resolve => { release = resolve; });
const methods = [];
const reopened = cache(async method => { methods.push(method); await blocked; return reply('new'); });
const slowRead = reopened.read('snapshot');
const fast = await Promise.race([reopened.peek(), new Promise((_,reject) => setTimeout(() => reject(Error('startup waited for network')), 300))]);
assert.equal(fast.value.issues[0].title, 'original');
assert.equal(fast.value.fromCache, true);
assert.equal(fast.value.updatedAt, 'original-time');
await reopened.peek();
await new Promise(resolve => setImmediate(resolve));
assert.deepEqual(methods, ['snapshot'], 'cache hydration does not launch duplicate network reads');
release(); await slowRead;
assert.equal((await reopened.read('snapshot')).value.issues[0].title, 'new');

identity = 'binding-b';
assert.equal(await reopened.peek(), null);
let fetched = 0;
assert.equal((await cache(async () => { fetched++; return reply('binding-b'); }).read('snapshot')).value.issues[0].title, 'binding-b');
assert.equal(fetched, 1, 'binding/config changes cannot replay old data');
const other = createProjectSnapshotCache({ directory, workspaceRoot: path.join(directory,'project-b'), identity: async () => identity, call: async () => ({ ok: true, value: { ok: false } }), now: () => time });
assert.equal((await other.read('snapshot')).value.ok, false, 'different project never receives cached project A');
assert.equal(await other.peek(), null);

let releaseOld;
const oldRead = cache(async () => { await new Promise(resolve => { releaseOld = resolve; }); return reply('before mutation'); });
const inFlight = oldRead.read('refresh');
while (!releaseOld) await new Promise(resolve => setImmediate(resolve));
await cache(async () => reply('unused')).invalidate();
releaseOld(); await inFlight;
assert.equal(await cache(async () => reply('unused')).peek(), null);
let afterMutation = 0;
const fresh = cache(async () => { afterMutation++; return reply('after mutation'); });
assert.equal((await fresh.read('snapshot')).value.issues[0].title, 'after mutation');
assert.equal(afterMutation, 1, 'in-flight result cannot repopulate cache across another worker mutation');
const finishA=await fresh.beginMutation();
const concurrent=cache(async()=>reply('concurrent'));
const finishB=await concurrent.beginMutation();
assert.equal(await concurrent.peek(),null);
await concurrent.read('snapshot');
await finishA();
assert.equal(await fresh.peek(),null,'second writer still disables cache reuse');
await finishB();
assert.equal(await fresh.peek(),null,'read taken during a mutation is not persisted');
await fresh.read('snapshot');
assert.ok(await fresh.peek());

const forceMethods=[];
await cache(async method => { forceMethods.push(method); return reply('forced'); }).read('refresh');
await cache(async method => { forceMethods.push(method); return reply('hinted'); }).read('snapshot', { backendId: 'github' });
assert.deepEqual(forceMethods, ['refresh','snapshot']);
time += 300001;
assert.equal(await fresh.peek(), null);
let expired=0;
await cache(async () => { expired++; return reply('expired'); }).read('snapshot');
assert.equal(expired,1);
const file=path.join(directory,'panel-startup-snapshot.json');
const entry=JSON.parse(await readFile(file,'utf8'));entry.project='wrong-project';await writeFile(file,JSON.stringify(entry));
assert.equal(await fresh.peek(), null);
let malformed=0;
await cache(async()=>{malformed++;return reply('safe');}).read('snapshot');
assert.equal(malformed,1);
console.log('PASS cache hydration does not wait for blocked network or replace fresh reply; original timestamp preserved');
console.log('PASS project/config/mutation isolation; stale in-flight result rejected; forced/hinted/expired reads bypass cache');
